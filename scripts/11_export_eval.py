ORDER = ["正确", "部分正确", "错误"]


def main():
    data = json.load(open(os.path.join(OUT, "eval_raw.json"), encoding="utf-8"))

    tally = {}
    for r in data:
        v = VERDICT[r["id"]][0]
        tally[v] = tally.get(v, 0) + 1

    L = []
    L.append("# 10 题逐题评测记录")
    L.append("")
    L.append("数据源：`out/eval_raw.json`，由 `scripts/08_eval.py` 实际跑出来"
             "（检索 top-8、混合模式 hybrid、带 LLM 生成）。")
    L.append("")
    L.append("**判定口径**：`auto_pass` 只查「标准答案里的数字有没有出现在回答中」，是初筛；"
             "下面每题的人工判定是**逐个读过模型回答和召回块**之后给的。")
    L.append("")
    L.append("**页码口径**：下表「页码」取检索块的 `page` 字段（分块时从报告页眉/页脚取的页号）；"
             "速查表是人工汇总、没有页码，记作「—」。")
    L.append("")
    L.append("**总账**：" + "、".join(f"{k} {tally.get(k,0)} 题" for k in ORDER) +
             f"（共 {len(data)} 题）。")
    L.append("")
    L.append("题目构成：8 道单公司题 + 2 道跨公司全景题（第 9、10 题）。")
    L.append("")

    # 汇总表
    L.append("| 题 | 类型 | 判定 | 关键证据 |")
    L.append("| --- | --- | --- | --- |")
    SHORT = {
        1: "速查表；锡装自己的原文块没进 top-8",
        2: "华工第二节 p6 + 第八节 p7 原文表（top-1、2）",
        3: "万华第八节 p7 / p137 原文表（top-8 里 4 块）",
        4: "中国巨石第二节 p6 原文表（top-1）",
        5: "亨通第二节 p6（top-1），但回答主要引速查表",
        6: "江淮第八节 p35/36/128/129 原文表；但措辞与原文口径不符",
        7: "锡业第三节 p18 原文块（top-4）",
        8: "命中 p14「变动原因」空表（top-1、5），有答案的叙述段未进 top-8",
        9: "全靠速查表；无原文块能同时含 14 家",
        10: "全靠速查表（top-1~3）",
    }
    for r in data:
        v = VERDICT[r["id"]][0]
        L.append(f"| {r['id']} | {r['type']} | **{v}** | {SHORT[r['id']]} |")
    L.append("")
    L.append("---")
    L.append("")

    for r in data:
        v, why = VERDICT[r["id"]]
        L.append(f"## 第 {r['id']} 题（{r['type']}）")
        L.append("")
        L.append(f"**问**：{r['q']}")
        L.append("")
        L.append(f"**标准答案**：{r['std']}")
        L.append("")
        L.append("**表格口径**：合并报表、报告期累计；金额单位元（速查表另附亿元口径）。")
        L.append("")
        L.append(f"**判定：{v}**")
        L.append("")
        L.append(f"理由：{why}")
        L.append("")
        L.append("**模型的实际回答（原文照录）**：")
        L.append("")
        L.append("```")
        L.append(r["answer"].strip())
        L.append("```")
        L.append("")
        L.append("**召回证据（融合后的 top-8）**：")
        L.append("")
        L.append("| # | 来源 | 代码 | 章节 | 页码 | 分数 |")
        L.append("| --- | --- | --- | --- | --- | --- |")
        for h in r["hits"]:
            nm = h["name"]
            if h["code"] == "SUMMARY":
                nm += "（人工汇总，非检索所得）"
            L.append(f"| {h['n']} | {nm} | {h['code']} | {h['section']} | {h['page']} | {h['score']:.4f} |")
        L.append("")
        L.append(f"自动初筛 `auto_pass` = `{r['auto_pass']}`，逐项命中情况：`{json.dumps(r['num_hits'], ensure_ascii=False)}`")
        L.append("")
        L.append("---")
        L.append("")

    out = os.path.join(OUT, "10题评测记录.md")
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("->", out)
    print("总账：" + "、".join(f"{k} {tally.get(k,0)} 题" for k in ORDER))


if __name__ == "__main__":
    main()
